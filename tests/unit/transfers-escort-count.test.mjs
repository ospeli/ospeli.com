// Guide rule 3 counts delay and cancel events, not journeys (logic.js lines 415-418), but its level
// is "three journeys" and its text says "N journeys were held up". One journey delayed three times
// for no escort and then cancelled for it is reported to the manager as 4 journeys.
test('one journey delayed three times for no escort, then cancelled for it, is one journey, not four', () => {
  const ev = [ask('trf-00001', at('15:00')),
    ...['15:05', '15:30', '16:10'].map((hm) => e('transfers.delayed', 'trf-00001', at(hm), { reason: 'no-escort' }, 'transport-coordinator')),
    e('transfers.cancelled', 'trf-00001', at('16:30'), { reason: 'no-escort' }, 'transport-coordinator')];
  const r = ruleEscortCover({ transfers: deriveTransfers(ev), now: at('18:00'), offsetMinutes: 0 });
  assert.deepEqual(r.map((x) => x.text), [], 'one journey is below the level of three, so the rule stays quiet');
});
